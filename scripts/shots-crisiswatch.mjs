import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser = await chromium.launch({channel:'chromium',args:['--use-angle=d3d11','--ignore-gpu-blocklist']});
const page = await browser.newPage({viewport:{width:1440,height:900}});
page.on('pageerror',e=>console.log('ERROR',e.message));
await page.goto('http://localhost:4173/os/embed.html?embed=1');
await page.locator('.desk-icon').first().waitFor();
await page.waitForTimeout(800);
for (const close of await page.locator('.os-window [data-close]').all()) await close.click();
await page.locator('.desk-icon').filter({hasText:'CrisisWatch'}).first().click();
const win=page.locator('.os-window').filter({hasText:'CrisisWatch'}).last();
const frame=await (await win.locator('iframe').elementHandle()).contentFrame();
await frame.locator('h1').waitFor();
await page.waitForTimeout(3500);
console.log('font',await frame.locator('body').evaluate(el=>getComputedStyle(el).fontFamily));
const confidence = await frame.evaluate(async()=>{
  const response=await fetch('/api/check',{method:'POST',body:JSON.stringify({claim:'NASA earthquake example'})});
  return (await response.json()).data.confidence;
});
assert.equal(confidence,96,'REST fixture uses percentage confidence');
await page.screenshot({path:'scripts/shots/crisiswatch-final-home.png'});
await frame.getByRole('link',{name:'Cap Check',exact:true}).click();
await page.waitForTimeout(1500);
await frame.getByRole('button').filter({hasText:'NASA said a 7.8 magnitude earthquake'}).click();
await frame.waitForFunction(()=>/THAT.?S CAP|FALSE/.test(document.body.innerText),null,{timeout:10000});
await frame.waitForFunction(()=>/96%/.test(document.body.innerText)&&!document.body.innerText.includes('9600%'));
await page.waitForTimeout(1500);
await page.screenshot({path:'scripts/shots/crisiswatch-final-result.png'});
await browser.close();
