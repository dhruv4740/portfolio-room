import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser = await chromium.launch({channel:'chromium',args:['--use-angle=d3d11','--ignore-gpu-blocklist']});
const page = await browser.newPage({viewport:{width:1536,height:864},deviceScaleFactor:1.25});
page.on('pageerror', e=>console.log('PAGE ERROR',e.message));
await page.addInitScript(()=>{localStorage.setItem('v3:surface-override','scan');localStorage.setItem('v3:seen-intro','1');localStorage.setItem('v3:test','1');localStorage.setItem('v3:perf-tier','mid');sessionStorage.setItem('v3:controls','open');});
await page.goto('http://localhost:4173/?sky=night');
await page.waitForTimeout(2500);
await page.addStyleTag({content:'.telemetry-root{display:none!important}'});
await page.screenshot({path:'scripts/shots/studio-overview.png'});
await page.locator('[data-launchpad-action="explore-room"]').click();
await page.waitForTimeout(1500);
await page.screenshot({path:'scripts/shots/studio-seat.png'});
console.log('perf',await page.evaluate(()=>window.__v3test?.perf()));
await page.getByRole('button',{name:'WINDOW',exact:true}).click();
await page.waitForTimeout(200);
await page.keyboard.press('Escape');
await page.waitForTimeout(1200);
assert.equal(await page.locator('.workspace-stage').getAttribute('data-window-open'),'1','Back finishes opening the window');
await page.getByRole('button',{name:'WINDOW',exact:true}).click();
await page.waitForTimeout(900);
await page.getByRole('button',{name:'WINDOW',exact:true}).click();
await page.waitForTimeout(1700);
await page.screenshot({path:'scripts/shots/studio-window.png'});
await page.keyboard.press('Escape');
await page.getByRole('button',{name:'BACK TO OVERVIEW',exact:true}).click();
await page.locator('[data-launchpad-action="desktop-projects"]').click();
await page.waitForFunction(()=>document.querySelector('.scan-root')?.dataset.entranceState==='inside');
await page.screenshot({path:'scripts/shots/studio-catalog.png'});
await page.locator('[data-testid="back-to-room"]').click();
await page.locator('[data-launchpad-action="mobile-projects"]').click();
await page.locator('.phone-presentation--stage').waitFor();
await page.waitForTimeout(400);
assert.equal(await page.locator('.phone-presentation--stage').getAttribute('aria-modal'),'true');
await page.screenshot({path:'scripts/shots/studio-phone.png'});
await browser.close();
