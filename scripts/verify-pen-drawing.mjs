// Pen: picking it up enters drawing mode over the notebook; dragging leaves ink
// on the page, the notebook shows it when lifted, and CLEAR PAGE wipes it.
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
const BASE = process.env.BASE || 'http://localhost:4173';
const b = await chromium.launch(process.env.GPU === '1' ? { channel: 'chromium', args: ['--use-angle=d3d11', '--ignore-gpu-blocklist'] } : {});
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
const errors = []; p.on('pageerror', e => errors.push(e.message));
await p.addInitScript(() => { localStorage.setItem('v3:test', '1'); localStorage.setItem('v3:surface-override', 'scan'); localStorage.setItem('v3:seen-intro', '1'); localStorage.setItem('v3:perf-tier', 'low'); });
await p.goto(BASE + '/?sky=day'); await p.waitForTimeout(3000);
await p.locator('[data-testid="room-overview"]').waitFor(); await p.locator('[data-launchpad-action="explore-room"]').click(); await p.waitForTimeout(2500);
const state = v => p.waitForFunction(v => document.querySelector('.workspace-stage')?.dataset.actionState === v, v, { polling: 100, timeout: 20000 });
await p.getByRole('button', { name: 'PEN', exact: true }).click();
await p.waitForTimeout(500); await p.screenshot({ path: 'scripts/shots/pen-pickup.png' });
await state('drawing'); await p.waitForTimeout(400);
assert.equal(await p.evaluate(() => window.__v3test.inkPixels()), 0, 'page starts blank');
const c = await p.evaluate(() => window.__v3test.projectAnchor('notebook'));
await p.mouse.move(c.x - 90, c.y - 40); await p.mouse.down();
for (let i = 0; i <= 20; i++) await p.mouse.move(c.x - 90 + i * 9, c.y - 40 + Math.sin(i / 3) * 30);
await p.mouse.up(); await p.waitForTimeout(300);
const ink = await p.evaluate(() => window.__v3test.inkPixels());
console.log('ink pixels after stroke', ink); assert.ok(ink > 500, 'stroke left ink');
await p.screenshot({ path: 'scripts/shots/pen-drawing.png' });
assert.equal(await p.locator('.workspace-stage').evaluate(e => e.dataset.actionState), 'drawing', 'drag did not leave drawing mode');
console.log('PASS pen draws on the page');
await p.keyboard.press('Escape'); await state('idle'); await p.waitForTimeout(500);
await p.getByRole('button', { name: 'NOTEBOOK', exact: true }).click();
await p.waitForFunction(() => document.querySelector('.workspace-stage')?.dataset.notebookState === 'reading', null, { polling: 100 });
await p.waitForTimeout(400); await p.screenshot({ path: 'scripts/shots/pen-notebook-held.png' });
await p.keyboard.press('Escape'); await p.waitForFunction(() => document.querySelector('.workspace-stage')?.dataset.notebookState === 'desk', null, { polling: 100 });
await p.waitForTimeout(800);
await p.getByRole('button', { name: 'PEN', exact: true }).click(); await state('drawing');
await p.getByRole('button', { name: 'CLEAR PAGE' }).click();
assert.equal(await p.evaluate(() => window.__v3test.inkPixels()), 0, 'clear page wipes ink');
console.log('PASS clear page');
await p.keyboard.press('Escape'); await state('idle');
assert.deepEqual(errors, []);
console.log('pen drawing passed');
await b.close();
